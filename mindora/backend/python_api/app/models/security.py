"""Security & monitoring models (Phase 7.1)."""
from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import Boolean, DateTime, ForeignKey, String, Text
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


# ---------- Alert types / severity ----------

ALERT_TYPE_FAILED_LOGIN = "failed_login"
ALERT_TYPE_SUSPECT_IP = "suspect_ip"
ALERT_TYPE_BULK_ACTION = "bulk_action"
ALERT_TYPE_PERMISSION_CHANGE = "permission_change"
ALERT_TYPE_MANUAL = "manual"

ALERT_TYPES = (
    ALERT_TYPE_FAILED_LOGIN,
    ALERT_TYPE_SUSPECT_IP,
    ALERT_TYPE_BULK_ACTION,
    ALERT_TYPE_PERMISSION_CHANGE,
    ALERT_TYPE_MANUAL,
)

ALERT_SEVERITY_LOW = "low"
ALERT_SEVERITY_MEDIUM = "medium"
ALERT_SEVERITY_HIGH = "high"
ALERT_SEVERITY_CRITICAL = "critical"

ALERT_SEVERITIES = (
    ALERT_SEVERITY_LOW,
    ALERT_SEVERITY_MEDIUM,
    ALERT_SEVERITY_HIGH,
    ALERT_SEVERITY_CRITICAL,
)


class AdminLoginHistory(Base):
    """Every login attempt (success or failure) — admin + user."""
    __tablename__ = "admin_login_history"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    user_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    email: Mapped[str] = mapped_column(String(255), nullable=False, index=True)
    ip: Mapped[str | None] = mapped_column(String(64), nullable=True, index=True)
    user_agent: Mapped[str | None] = mapped_column(String(500), nullable=True)
    success: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True, index=True)
    failure_reason: Mapped[str | None] = mapped_column(String(120), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=datetime.utcnow, nullable=False, index=True
    )


class SecurityAlert(Base):
    """An alert generated by the system or manually."""
    __tablename__ = "security_alerts"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    type: Mapped[str] = mapped_column(String(40), nullable=False, index=True)
    severity: Mapped[str] = mapped_column(
        String(20), nullable=False, default=ALERT_SEVERITY_MEDIUM, index=True
    )
    message: Mapped[str] = mapped_column(Text, nullable=False)
    # Metadata JSONB — e.g. {"ip": "1.2.3.4", "email": "a@b.c", "count": 5}
    metadata_json: Mapped[dict] = mapped_column(
        JSONB, nullable=False, default=dict, name="metadata"
    )
    acknowledged: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=False, index=True
    )
    acknowledged_by: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
    )
    acknowledged_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=datetime.utcnow, nullable=False, index=True
    )
